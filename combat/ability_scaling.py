"""How an ability grows with level and with the caster's power.

Kyle, 15 Nov 2026: "Player damage is rather low. There's very little skill difference between lvl 15 skills and
lvl 60." and "We need to look at scaling and also how spell power, healing power, or attack power scale to a
spell". A friend at endgame: "I just do so little damage and they hit me hard".

MEASURED FIRST (tools/sim_ability_scaling.py prints it again):

  * Ranks: every main attack and heal was exactly 2x as strong at 56 as at 12-15. Fireball 66 -> 132, Heroic
    Strike 66 -> 132, Smite 63 -> 126. Over the same levels a same-level mob's health grows ~4x and its damage
    ~5x, so fights got longer and casters folded (a level-60 Mage won 2 of 6 against ONE normal mob).
  * Power: one flat number for everything. Every spell added 1.5x spell power, every heal 1.2x healing power,
    every physical special 0.5x attack power, every DoT 1.0x spell power (0.3x attack power) over its whole
    duration. Searing Pain scaled exactly like Pyroblast; Arcane Explosion like Frostbolt.

Kyle chose (15 Nov): fights stay ~3-4 casts at every level, with ranks growing ~4x from 15 to 60; and power
scaling per ability, WoW-style.

TWO RULES, applied where abilities are built (abilities._ability_from_data) rather than written into the 30
class files, because those files are regenerated by their build_* tools and a data rewrite would quietly be
undone the next time one ran. Data can still override either rule per ability.

1. THE RANK CURVE. A rank's strength (effect_value, heal_value, absorb) is multiplied by rank_multiplier of the
   level that rank is learned at: how far normal monsters' health has grown past the authored rank line by
   then (x1 at 1, x2 at 15, x3 at 56 - see the constants). Only for effect types whose effect_value IS a strength (damage, heals,
   DoTs, HoTs, shields); a buff's effect_value can be a percentage and is left alone.

2. POWER COEFFICIENTS, per ability, from what the ability is:
     base for its kind (a direct spell, a heal, a physical special, a DoT, a HoT)
     x weight from its cooldown (a spammable cast is the base; a big cooldown hit takes more)
     x a share for area effects (an AoE or a party heal pays per target, so each target gets less).
   A DoT or HoT's coefficient is its TOTAL across every tick, like its effect_value.

CALIBRATED (15 Nov) with tools/sim_class_balance.py, all 30 classes with talents spent, against the old flat
rules. Turns to kill a same-level enemy, median [range]:
    old:            lv20 4.5 [3.2-7.9]   lv40 4.0 [2.2-6.2]   lv60 4.3 [2.4-7.5]
    gains 1.0/1.5:                       lv40 3.2 [1.9-4.5]   lv60 2.7 [1.3-3.9]   too fast with talents
    gains 0.6/1.0:                       lv40 3.5             lv60 3.0 [1.6-4.8]   chosen: "3-4 casts"
Per-class outliers are the class pass's job, not these constants'.

3. HIGHER RANKS TAKE MORE OF YOUR POWER, Classic's way (Kyle, 15 Nov 2026): a rank learned below 20 takes 3.75%
   less of its coefficient per level short of 20, and a rank the caster has outlevelled is downrank-penalized.
   See section 3 below.
"""

#: ---- 1. the rank curve: RANKS GROW WITH THE MONSTERS (Kyle, 15 Nov 2026, second pass)
#: "Bro I don't think ranks are scaling! ... his lvl 60 spells are still baseline of 130 when they start at like 70"
#: and "a Healer should not fucking heal the same 14 levels later", pointing at Classic's Lightning Bolt: ~20 at
#: rank 1, 430-470 at the rank taught at 56, before spell power. Measured: a normal monster's health goes 120 at
#: level 1 -> 1,182 at 60 (~10x, linear: +15% of the level-1 value a level), while the authored ranks go 3x
#: (Fireball 44 -> 132, +3.6% a level) - gear was quietly covering the gap and the ranks looked like nothing. The
#: first curve (this morning) started at level 20 and was damped to x1.6, so levels 1-20 got nothing.
#: Now a rank's strength is multiplied by how far the monsters have grown past the authored line at the level it is
#: learned: x1 at 1, x2 at 15, x3 at 56. Fireball at 56: 132 -> ~407 (Classic Lightning Bolt: 430-470).
MONSTER_HP_SLOPE = 0.15        # normal monster health, per level, as a share of level 1's (entities/monster.py)
AUTHORED_SLOPE = 0.03636       # the authored rank line, per level, as a share of rank 1's (44 -> 132 over 1-56)
RANK_CURVE_FROM = 1


def rank_multiplier(level_req):
    """How much stronger a rank learned at this level is than its authored value: the world's growth
    (combat/world_curve.py) over the authored line's, at the level the rank is learned.

    Third pass (Kyle, 15 Nov 2026, "Steeper world": "Each spell rank or ability rank should FEEL like an actual
    step"): the world now compounds like Classic's, so a rank is ~+100% early and +23% late, and a top rank is
    ~25x rank 1 (Fireball 44 -> ~1,100 at 56; Classic Lightning Bolt 16 -> 452, Healing Touch 47 -> 2,472)."""
    if not RANK_CURVE_ON:
        return 1.0
    from combat.world_curve import growth
    lv = max(1, level_req or 1)
    return growth(lv) / (1 + AUTHORED_SLOPE * (lv - 1))


RANK_CURVE_ON = True


#: effect types whose effect_value is a strength, so ranks scale
CURVED = frozenset({"damage", "spell_damage", "ranged_damage", "dot", "spell_dot", "heal", "hot",
                    "damage_and_heal", "damage_and_restore_mana"})


# ---- 4. mana costs, normalized per class (Kyle, 15 Nov: "~20 turns", "Normalize per class")
#: data/balance/mana_costs.json, written by tools/calibrate_mana_costs.py: per class, a cost multiplier by level for
#: its damage spells and for its heals, chosen so the class's main spell lasts MANA_TARGET_TURNS from a full bar.
#: Every other mana ability in the class moves by the same factor, so the class's own cost ratios survive.
_MANA_TABLE = None
HEAL_KINDS = frozenset({"heal", "hot", "damage_and_heal"})


def _mana_table():
    global _MANA_TABLE
    if _MANA_TABLE is None:
        try:
            import json
            from pathlib import Path
            _MANA_TABLE = json.loads((Path(__file__).resolve().parent.parent / "data/balance/mana_costs.json")
                                     .read_text(encoding="utf-8")).get("classes", {})
        except (OSError, ValueError):
            _MANA_TABLE = {}
    return _MANA_TABLE


def _class_of(ability_id):
    best = None
    for slug in _mana_table():
        if ability_id.startswith(slug + "_") and (best is None or len(slug) > len(best)):
            best = slug
    return best


def mana_cost_multiplier(ability_id, effect_type, level_req):
    table = _mana_table()
    slug = _class_of(ability_id or "")
    if not slug:
        return 1.0
    points = table[slug].get("heal" if effect_type in HEAL_KINDS else "damage") or table[slug].get("damage") or []
    if not points:
        return 1.0
    lv = level_req or 1
    if lv <= points[0][0]:
        return points[0][1]
    for (a, fa), (b, fb) in zip(points, points[1:]):
        if a <= lv <= b:
            return fa + (fb - fa) * (lv - a) / max(1, b - a)
    return points[-1][1]


# ---- 5. spec auras (Kyle, 15 Nov: "I don't want classes to be wildly different. Like a balance druid spamming wrath
# or starfire shouldn't absolutely blow past an elemental shaman spamming lightning bolt or a stormbringer spamming
# shock" - he picked "within ~10%", with uniqueness from utility, procs, AoE, DoTs and cooldowns).
#: data/balance/spec_auras.json, written by tools/calibrate_spec_auras.py: {"damage": {spec: [[level, x], ...]},
#: "healing": {...}}. A hidden multiplier on everything a character of that spec deals (or heals), by level -
#: WoW's own tool for this ("Fire Specialization"). Clamped to AURA_RANGE when written: a spec that needs more
#: than that is a broken kit to fix by hand, not a number to hide.
_AURAS = None
USE_SPEC_AURAS = True
#: A spec that would need more than the top is a broken kit to fix by hand (Feral had no combo points, Enhancement's
#: Stormstrike hit for nothing); a spec below the bottom stacks far past its peers and gets its tree looked at.
#: Turning a strong spec down quietly is fine; propping a broken one up hides it - hence the lopsided range.
AURA_RANGE = (0.35, 1.75)


def _aura_table():
    global _AURAS
    if _AURAS is None:
        try:
            import json
            from pathlib import Path
            _AURAS = json.loads((Path(__file__).resolve().parent.parent / "data/balance/spec_auras.json")
                                .read_text(encoding="utf-8"))
        except (OSError, ValueError):
            _AURAS = {}
    return _AURAS


def _interp(points, lv):
    if not points:
        return 1.0
    if lv <= points[0][0]:
        return points[0][1]
    for (a, fa), (b, fb) in zip(points, points[1:]):
        if a <= lv <= b:
            return fa + (fb - fa) * (lv - a) / max(1, b - a)
    return points[-1][1]


def spec_aura(caster, kind="damage"):
    """The hidden spec multiplier for a character's outgoing damage or healing (1.0 for anyone without a spec)."""
    if not USE_SPEC_AURAS or not hasattr(caster, "talent_trees"):
        return 1.0
    table = _aura_table().get(kind) or {}
    if not table:
        return 1.0
    try:
        from entities.proficiency import active_spec
        spec = active_spec(caster)
    except Exception:                                          # noqa: BLE001
        return 1.0
    if spec not in table:
        return 1.0
    return _interp(table[spec], getattr(caster, "level", 1) or 1)


def curved_ranks(entry):
    """The entry's ranks with the curve applied (a new list; the data is never edited in place)."""
    ranks = entry.get("ranks") or []
    et = entry.get("effect_type")
    out = []
    for r in ranks:
        m = rank_multiplier(r.get("level_req", 1))
        r = dict(r)
        if et in CURVED and r.get("effect_value"):
            r["effect_value"] = int(round(r["effect_value"] * m))
        if r.get("heal_value"):
            r["heal_value"] = int(round(r["heal_value"] * m))
        if r.get("absorb"):
            r["absorb"] = int(round(r["absorb"] * m))
        if r.get("cost") and entry.get("resource_type", "mana") == "mana" and USE_MANA_TABLE:
            r["cost"] = max(1, int(round(r["cost"] * mana_cost_multiplier(entry.get("ability_id"), et,
                                                                         r.get("level_req", 1)))))
        out.append(r)
    return out


#: the calibration tool switches this off to read the authored costs
USE_MANA_TABLE = True

#: ---- 2. power coefficients. The base is a spammable single-target cast of that kind.
SP_BASE = 1.5            # direct spell damage, per point of spell power
HEAL_BASE = 1.2          # direct heal, per point of healing power
AP_BASE = 0.5            # physical special, per point of attack power (the weapon roll is on top)
DOT_SP_BASE = 1.0        # a spell DoT, total over its duration
DOT_AP_BASE = 0.3        # a physical DoT (a bleed), total
HOT_BASE = 0.8           # a HoT, total

#: cooldown (turns) -> weight. A cast you can only make every few turns carries more of your power,
#: the way a long cast time does in WoW.
COOLDOWN_WEIGHTS = [(8, 1.7), (5, 1.45), (3, 1.25), (2, 1.1), (0, 1.0)]

AOE_SHARE = 0.5          # unlimited targets
AOE_SMALL_SHARE = 0.7    # two or three targets


def cooldown_weight(cooldown):
    cd = cooldown or 0
    return next(w for at, w in COOLDOWN_WEIGHTS if cd >= at)


def area_share(target_type, max_targets=None, heal_scope=None):
    if target_type == "enemy_aoe" or target_type == "party" or heal_scope == "party":
        if max_targets and max_targets <= 3:
            return AOE_SMALL_SHARE
        return AOE_SHARE
    return 1.0


#: ---- 3. power share by rank: HIGHER RANKS TAKE MORE OF YOUR POWER (Kyle, 15 Nov 2026: "Higher rank spells scale
#: more from spell power, attack power, and healing power than low rank ones do. Wow also does this")
#: Classic's two rules, both here, for spells, heals and physical specials alike:
#:   LOW-LEVEL PENALTY - a rank learned below level 20 gets 3.75% less of the coefficient per level short of 20:
#:       learned at 1 -> 29%, at 10 -> 62.5%, at 20 or later -> all of it.
#:   DOWNRANK PENALTY  - a rank the caster has outlevelled (an untrained player still on rank 1, or an old rank) is
#:       scaled by (the level just before the next rank + 6) / caster level, capped at 1. The rank you SHOULD have
#:       at your level is never penalized; rank 1 cast at 40 takes about a sixth of your power.
LOW_LEVEL_PENALTY_BELOW = 20
LOW_LEVEL_PENALTY_PER_LEVEL = 0.0375
DOWNRANK_GRACE = 6


def low_level_penalty(level_req):
    lr = max(1, level_req or 1)
    return max(0.0, 1.0 - max(0, LOW_LEVEL_PENALTY_BELOW - lr) * LOW_LEVEL_PENALTY_PER_LEVEL)


def downrank_penalty(ability, caster_level):
    """(the level before the next rank + 6) / caster level, capped at 1. None for the top rank."""
    if not caster_level:
        return 1.0
    try:
        ranks = ability.ranks
        nxt = ranks[ability.current_rank_index + 1]["level_req"] if ability.current_rank_index + 1 < len(ranks) else None
    except Exception:                                          # noqa: BLE001
        return 1.0
    if nxt is None:
        return 1.0
    return min(1.0, (nxt - 1 + DOWNRANK_GRACE) / caster_level)


def rank_power_multiplier(ability, kind=None, caster_level=None):
    try:
        level_req = ability.current_rank.get("level_req", 1)
    except Exception:                                          # noqa: BLE001
        level_req = 1
    return low_level_penalty(level_req) * downrank_penalty(ability, caster_level)


def coefficient(ability, kind, caster=None):
    """The coefficient this ability casts with RIGHT NOW: its own, times its current rank's share (above)."""
    base = getattr(ability, KIND_ATTR[kind], None)
    if base is None:
        base = DEFAULTS[kind]
    if getattr(ability, "fixed_coefficients", None) and kind in ability.fixed_coefficients:
        return base
    if not USE_RANK_POWER:
        return base
    return base * rank_power_multiplier(ability, kind, getattr(caster, "level", None))


USE_RANK_POWER = True


KIND_ATTR = {"sp": "sp_coefficient", "heal": "heal_coefficient", "ap": "ap_coefficient",
             "dot_sp": "dot_sp_coefficient", "dot_ap": "dot_ap_coefficient", "hot": "hot_coefficient"}
DEFAULTS = {"sp": 1.5, "heal": 1.2, "ap": 0.5, "dot_sp": 1.0, "dot_ap": 0.3, "hot": 0.8}


def coefficients(ability):
    """{sp, heal, ap, dot_sp, dot_ap, hot} for this ability. Only the ones its effect type reads matter."""
    w = cooldown_weight(getattr(ability, "cooldown", 0)) * area_share(
        getattr(ability, "target_type", None), getattr(ability, "max_targets", None),
        getattr(ability, "heal_scope", None))
    return {"sp": SP_BASE * w, "heal": HEAL_BASE * w, "ap": AP_BASE * w,
            "dot_sp": DOT_SP_BASE * w, "dot_ap": DOT_AP_BASE * w, "hot": HOT_BASE * w}


def apply(ability, entry):
    """Set an ability's coefficients from the rules, unless its data names one."""
    c = coefficients(ability)
    fixed = set()
    for key, attr in KIND_ATTR.items():
        given = entry.get(attr)
        if given is not None:
            fixed.add(key)            # named in the data: used exactly, no rank growth
        setattr(ability, attr, float(given) if given is not None else c[key])
    ability.fixed_coefficients = fixed


