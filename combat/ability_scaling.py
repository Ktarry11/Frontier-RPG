#: ---- 2. power coefficients. The base is a spammable single-target cast of that kind.
SP_BASE = 1.5            # direct spell damage, per point of spell power
HEAL_BASE = 1.2          # direct heal, per point of healing power (the healing formula replaces it: see below)
AP_BASE = 0.5            # physical special, per point of attack power (the weapon roll is on top)
#: DoTs scaled at half a direct spell's share of power per point of base (a bleed at a third) - measured 27 Nov 2026
#: across every class at 60: direct spells 0.90 coefficient per 1,000 base, spell DoTs 0.49, physical specials 0.34,
#: bleeds 0.10. Kyle: "Damage-over-time abilities scale extremely poorly." Raised so a DoT takes the same share of
#: your power, against its size, as a direct hit of its kind.
DOT_SP_BASE = 1.85       # a spell DoT, total over its duration
DOT_AP_BASE = 1.0        # a physical DoT (a bleed), total
HOT_BASE = 0.8           # a HoT, total (the healing formula replaces it: see below)

#: cooldown (turns) -> weight. A cast you can only make every few turns carries more of your power,
#: the way a long cast time does in WoW.
COOLDOWN_WEIGHTS = [(8, 1.7), (5, 1.45), (3, 1.25), (2, 1.1), (0, 1.0)]

AOE_SHARE = 0.5          # unlimited targets
AOE_SMALL_SHARE = 0.7    # two or three targets


def cooldown_weight(cooldown):
    cd = cooldown or 0
    return next(w for at, w in COOLDOWN_WEIGHTS if cd >= at)


def area_share(target_type, max_targets=None, heal_scope=None):
    if target_type == "enemy_aoe" or target_type == "party" or heal_scope == "party":
        if max_targets and max_targets <= 3:
            return AOE_SMALL_SHARE
        return AOE_SHARE
    return 1.0


#: ---- 3. power share by rank: HIGHER RANKS TAKE MORE OF YOUR POWER (Kyle, 15 Nov 2026: "Higher rank spells scale
#: more from spell power, attack power, and healing power than low rank ones do. Wow also does this")
#: Classic's two rules, both here, for spells, heals and physical specials alike:
#:   LOW-LEVEL PENALTY - a rank learned below level 20 gets 3.75% less of the coefficient per level short of 20:
#:       learned at 1 -> 29%, at 10 -> 62.5%, at 20 or later -> all of it.
#:   DOWNRANK PENALTY  - a rank the caster has outlevelled (an untrained player still on rank 1, or an old rank) is
#:       scaled by (the level just before the next rank + 6) / caster level, capped at 1. The rank you SHOULD have
#:       at your level is never penalized; rank 1 cast at 40 takes about a sixth of your power.
LOW_LEVEL_PENALTY_BELOW = 20
LOW_LEVEL_PENALTY_PER_LEVEL = 0.0375
DOWNRANK_GRACE = 6


def low_level_penalty(level_req):
    lr = max(1, level_req or 1)
    return max(0.0, 1.0 - max(0, LOW_LEVEL_PENALTY_BELOW - lr) * LOW_LEVEL_PENALTY_PER_LEVEL)


def downrank_penalty(ability, caster_level):
    """(the level before the next rank + 6) / caster level, capped at 1. None for the top rank."""
    if not caster_level:
        return 1.0
    try:
        ranks = ability.ranks
        nxt = ranks[ability.current_rank_index + 1]["level_req"] if ability.current_rank_index + 1 < len(ranks) else None
    except Exception:                                          # noqa: BLE001
        return 1.0
    if nxt is None:
        return 1.0
    return min(1.0, (nxt - 1 + DOWNRANK_GRACE) / caster_level)


def rank_power_multiplier(ability, kind=None, caster_level=None):
    """The low-level penalty only bites while a HIGHER rank of the ability exists: the top rank - including any
    single-rank ability - always takes its full share. Found the same day it went in: the basic Attack, Shoot
    and Wand are one rank learned at level 1, so every class's white damage took 29% of its attack power at
    every level (a level-30 Rogue's Attack hit for ~100) and the classic physical kits, which lean on white
    damage between energy and mana, measured half the median."""
    try:
        level_req = ability.current_rank.get("level_req", 1)
        top = ability.current_rank_index >= len(ability.ranks) - 1
    except Exception:                                          # noqa: BLE001
        level_req, top = 1, True
    low = 1.0 if top else low_level_penalty(level_req)
    return low * downrank_penalty(ability, caster_level)


def coefficient(ability, kind, caster=None):
    """The coefficient this ability casts with RIGHT NOW: its own, times its current rank's share (above)."""
    base = getattr(ability, KIND_ATTR[kind], None)
    if base is None:
        base = DEFAULTS[kind]
    if getattr(ability, "fixed_coefficients", None) and kind in ability.fixed_coefficients:
        return base
    if not USE_RANK_POWER:
        return base
    # A PET's abilities are authored as one rank at level 1 and grown with the pet (entities/pet.py
    # _scale_ability_power), so its rank is effectively learned at its own level: no low-level penalty.
    if getattr(caster, "char_class", None) == "Pet":
        return base
    return base * rank_power_multiplier(ability, kind, getattr(caster, "level", None))


USE_RANK_POWER = True


KIND_ATTR = {"sp": "sp_coefficient", "heal": "heal_coefficient", "ap": "ap_coefficient",
             "dot_sp": "dot_sp_coefficient", "dot_ap": "dot_ap_coefficient", "hot": "hot_coefficient"}
DEFAULTS = {"sp": 1.5, "heal": 1.2, "ap": 0.5, "dot_sp": DOT_SP_BASE, "dot_ap": DOT_AP_BASE, "hot": 0.8}


def coefficients(ability):
    """{sp, heal, ap, dot_sp, dot_ap, hot} for this ability. Only the ones its effect type reads matter.

    Heals and HoTs take the healing formula's coefficient (combat/heal_formula.coefficient: rare gear at your level
    adds 40% of the base) and the same area share as their base, so gear is the same share of every heal."""
    cw = cooldown_weight(getattr(ability, "cooldown", 0))
    w = cw * area_share(getattr(ability, "target_type", None), getattr(ability, "max_targets", None),
                        getattr(ability, "heal_scope", None))
    heal_c, hot_c, hw = HEAL_BASE, HOT_BASE, w
    if USE_HEAL_FORMULA:
        from combat import heal_formula as _hf
        if _hf.enabled():
            c = _hf.coefficient()
            heal_c, hot_c = c, c * _hf.HOT_FACTOR
            hw = cw * _hf.area({"target_type": getattr(ability, "target_type", None),
                                "heal_scope": getattr(ability, "heal_scope", None),
                                "max_targets": getattr(ability, "max_targets", None)})
    return {"sp": SP_BASE * w, "heal": heal_c * hw, "ap": AP_BASE * w,
            "dot_sp": DOT_SP_BASE * w, "dot_ap": DOT_AP_BASE * w, "hot": hot_c * hw}


def apply(ability, entry):
    """Set an ability's coefficients from the rules, unless its data names one.

    CAST SPEED TAKES ITS SHARE OF POWER TOO (15 Nov 2026). Classic's coefficient is cast time / 3.5: Greater Heal
    (3s) takes 86% of +healing, Flash Heal (1.5s) 43%. Here only the BASE values were sized by cast speed (a slow
    cast 1.5x, a quick one 0.65x) and every cast took the same share of power, so with gear the gap closed - a
    geared Holy Light (slow, a cooldown, more mana) healed about what a normal-speed heal shot did (Kyle's check:
    Holy Light vs Tinker's Repair Shot). The coefficient is now multiplied by the same cast-speed value."""
    c = coefficients(ability)
    try:
        from combat.abilities import cast_speed_value
        speed = cast_speed_value(entry.get("cast_speed"))
    except Exception:                                          # noqa: BLE001
        speed = 1.0
    if speed != 1.0:
        c = {k: v * speed for k, v in c.items()}
    fixed = set()
    for key, attr in KIND_ATTR.items():
        given = entry.get(attr)
        if given is not None:
            fixed.add(key)            # named in the data: used exactly, no rank growth
        setattr(ability, attr, float(given) if given is not None else c[key])
    ability.fixed_coefficients = fixed


