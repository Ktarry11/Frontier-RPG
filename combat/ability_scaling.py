    RANK_CURVE_ON = False
    COOLDOWN_WEIGHTS = [(0, 1.0)]
    AOE_SHARE = AOE_SMALL_SHARE = 1.0
    USE_RANK_POWER = False
    USE_MANA_TABLE = False
    USE_SPEC_AURAS = False
