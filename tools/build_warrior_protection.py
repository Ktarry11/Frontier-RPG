#!/usr/bin/env python3
"""Rebuild Warrior Protection from the real 3.3.5a tree.

    PYTHONPATH=. python3 tools/build_warrior_protection.py

SOURCE: data/reference/wotlk/warrior.json (from Spell.dbc).
Worksheet: data/reference/wotlk_worksheets/warrior.md.

ROLE: shield tanking. Block, armour, threat, and the rage that comes from
being hit.

STANCE GATING IS USED HERE. Improved Defensive Stance is written "while in
Defensive Stance" and is now buildable as written - see the engine change
in entities/character.py:get_talent_effects, made while building Fury's
Improved Berserker Stance. Before it, get_talent_effects passed only
current_form, so a stance-gated TALENT silently did nothing even though a
stance-gated ABILITY worked fine.

IMPROVED THUNDER CLAP COMES BACK HERE, where the real game puts it (row
0). The Arms rebuild had kept it as a documented placement departure
because the outgoing Arms tree carried it; it is removed from Arms in the
same commit, so it exists once, in the right tree, rather than twice and
stacking.

MISSING ABILITIES THIS TREE'S REAL TALENTS ARE WRITTEN ON: Revenge, Shield
Block, Shield Slam, Spell Reflection, Intervene, Shield Bash, Heroic
Throw. That is seven, more than any other tree in the project, and it is
why Protection has the most substitutions. Each is recorded on its node.

UNIT CONVENTIONS, probed:

    block, dodge, expertise            PERCENTAGE POINTS
    strength_pct, stamina_pct          PERCENTAGE POINTS (character.py:1262)
    armor_pct                          FRACTION as a talent effect
    max_health_pct                     FRACTION. Read at character.py:1411
                                       off `bonuses` WITHOUT dividing by
                                       100 - verified live, 636 -> 750 at
                                       0.18. The probe finds no literal
                                       read site because that line does not
                                       call get_talent_effect.
    physical_damage                    FRACTION
    magic_damage_taken_pct             FRACTION as a talent effect, NEGATIVE
    spell_damage_taken_pct             reduces
    damage_taken_pct                   RAW on both sides
    threat_generation_pct              FRACTION
    all_ability_cost_pct               FRACTION, and POSITIVE MEANS A
                                       REDUCTION. It also FLIPS - it is
                                       percentage POINTS inside a status
                                       effect - so only the talent-effect
                                       form is used here.

DEAD KEYS ROUTED AROUND: block_value_pct (Shield Mastery) - probed, zero
read sites. rage_generation_pct (Improved Bloodrage). Both deliver through
a key or proc that is read.

KEPT MANDATORY: Concussion Blow, Devastate and Shockwave are the only
unlocks for their abilities, all three requires_talent.
"""

