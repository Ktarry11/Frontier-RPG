"""Rebuild Bloodmage's Sanguine tree from the real CoA data.

    PYTHONPATH=. python3 tools/build_bloodmage_sanguine.py [--check]

SOURCE: data/reference/coa/bloodmage.json - 38 real Sanguine talents from
Ascension's own CoA Builder payload. Role: DPS. coa_playstyles.json:
"Warlock + Death Knight".

The shipped tree was 23 nodes with TWO procs and 19 bare numbers. Bloodmage
measures second-worst in the game after Witch Hunter: 81 of 92 nodes a bare
number across four specs.

THIRST IS VITALITY, and this is the one thing to understand before touching
this class. Bloodmage is dual-resource - Rage plus VITALITY - and Vitality
is CoA's Thirst: Bloodmoon Blast banks it (via that ability's `generates`
block) and Vampiric Fang spends 30 of it to steal health. I spent a while
convinced Vampiric Fang was uncastable, because Vitality is dict-backed and
starts at 0 and no talent or restore ability grants it. It is generated by
an ability instead, through a mechanism I had not checked - `generates`,
read at combat/abilities.py:995 and 2045. Verified before changing
anything, which is the only reason a working ability did not get
"fixed". tools/qa_ability_resources.py now checks this class of thing
directly so the next person does not have to retrace it.

WHAT THE SPEC IS. A caster that pays in its own blood: most of its spells
cost health, its DoTs tick, and its talents buy the health back - Hematoma
leeches off Bloodbolt, Dominion of Blood off Vampiric Fang, Cardiac Arrest
off Valanar's Vengeance.

THIRST-SCALING IS THE BIG LOSS, and it is engine-deep. Six CoA talents
scale off the CURRENT Thirst stack count - "each stack reduces the cast
time and increases damage", "each stack increases your critical strike
chance by 1%", "increases the duration of Animated Blood by 1 sec per
stack". Nothing in this engine reads a resource AMOUNT into a stat or an
effect: get_talent_effects() has no access to a live resource, and a proc
payload cannot scale off one either. Those six are flattened, each stated
on its node. The cast-time halves are gone regardless, since there are no
cast times.

CONVENTIONS, which do not agree with each other:
  haste, hit_rating, crit_chance_spell, ability_*_crit    PERCENT
  shadow_spell_damage, all_damage, dot_damage,
    crit_damage_spell, ability_*_damage                   FRACTION
  damage_dealt_pct in a status effect                     percentage POINTS
  <school>_damage_taken_pct in a status effect            percentage POINTS
  *_cost_pct / *_cooldown_pct       FRACTION, POSITIVE MEANS A REDUCTION
  <target>_from_<source>_pct        FRACTION, listed pairs only

TURN-BASED CUTS. Every cast time, every yard, and the "tick rate" halves
(ticks are per-turn here, so there is no sub-turn rate). Four CoA entries
in this export have broken template descriptions ($6a Transgression, $6c
Thirst, $6e Thirst for Blood, and Animated Blood is named by three talents
but has no entry at all) and are not built from a guess.
"""
