#!/usr/bin/env python3
"""Hand quests from overloaded givers to the people around them (backlog B [37]).

    PYTHONPATH=. python3 tools/apply_giver_moves.py [--check]

Kyle: "Some quest givers carry far too many quests... Two or three per giver, more givers."

data/reference/quest_giver_moves.json says which quest now belongs to whom. This writes it into the zone
quest files (giver_npc_id, and turn_in_npc_id where it named the old giver). The zone files are
generated by tools/build_*_quests.py; re-running one of those would hand the quest back, so
--check fails whenever the files and the moves disagree (it runs in the QA sweep through
tools/qa_quest_givers.py). The words for the new voice live in
data/quests/text/zzzzzz_giver_moves.json.
"""
import glob
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOVES = ROOT / "data" / "reference" / "quest_giver_moves.json"


def load_moves():
    return json.loads(MOVES.read_text(encoding="utf-8"))["moves"]


def apply(check=False):
    moves = load_moves()
    seen, todo = set(), []
    for path in sorted(glob.glob(str(ROOT / "data" / "quests" / "*.json"))):
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
        changed = False
        for q in doc.get("quests", []):
            m = moves.get(q["quest_id"])
            if not m:
                continue
            seen.add(q["quest_id"])
            old = q.get("giver_npc_id")
            if old != m["giver"]:
                todo.append(f"{q['quest_id']}: {old} -> {m['giver']}")
                if q.get("turn_in_npc_id") == old:
                    q["turn_in_npc_id"] = m["giver"]
                q["giver_npc_id"] = m["giver"]
                changed = True
        if changed and not check:
            Path(path).write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    missing = sorted(set(moves) - seen)
    return todo, missing


if __name__ == "__main__":
    check = "--check" in sys.argv
    todo, missing = apply(check)
    for t in todo:
        print(" ", t)
    for m in missing:
        print("  no such quest:", m)
    print(f"{len(todo)} giver change(s) {'to make' if check else 'made'}")
    sys.exit(1 if (check and (todo or missing)) else 0)
