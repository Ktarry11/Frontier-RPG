# Mage's shipped rank schedule - see module docstring.
RANK_LEVELS = [1, 6, 12, 18, 24, 32, 40, 48, 56]


def _levels(start, count):
    """Rank unlock levels: Mage's schedule from 1, else evenly up to 58.

    Nothing is ever placed above 58 - a rank above the level 60 cap never
    unlocks, which validate_class.py warns about and which would make a
    first rank unlearnable outright.
    """
    if start == 1:
        return RANK_LEVELS[:count]
    span = max(1, (58 - start) // max(1, count - 1)) if count > 1 else 1
    return [min(58, start + i * span) for i in range(count)]


def ranks(value, step, cost, cost_step, *, start=1, count=9, restore=None):
    """Mana-cost rank table: both the effect and the cost grow per rank.

    This is the Mage shape and the reason it differs from Guardian's flat
    Energy costs: a mana pool grows with level and gear, so a mana spell's
    rank 9 is meant to cost roughly three times its rank 1 (mage_fireball:
    30 -> 102). A flat cost would make late ranks free in practice.

    `restore` is a (base, step) pair for mana_restore_pct, which is read off
    the RANK dict rather than from effect_value - restore_resource abilities
    with no mana_restore_pct restore literally nothing.
    """
    out = []
    for i, level in enumerate(_levels(start, count)):
        rank = {
            "rank": i + 1,
            "level_req": level,
            "cost": int(round(cost + cost_step * i)),
            "effect_value": int(round(value + step * i)),
        }
        if restore:
            rank["mana_restore_pct"] = int(round(restore[0] + restore[1] * i))
        out.append(rank)
    return out


def one(level, cost, value=100, *, restore=None):
    """Single-rank table.

    effect_value defaults to 100, NOT 0. For a buff or debuff the engine
    scales every stat_mod by effect_value / 100 (see Ability._apply_effect),
    so a buff authored at 0 applies nothing at all - which is why all
    eighteen of Guardian's buff and debuff abilities currently grant
    nothing. 100 means "the stat_mods as written".
    """
    rank = {"rank": 1, "level_req": level, "cost": cost, "effect_value": value}
    if restore:
        rank["mana_restore_pct"] = restore[0]
    return [rank]


def scaling_buff(level, cost, count, *, step=14, level_step=12):
    """Rank table for a buff whose stat_mods should get stronger per rank.

    effect_value is the multiplier (100 = as written), so a buff scales by
    raising it: 100 / 114 / 128 ... Mage's Inner Fire does the same thing.
    """
    return [{"rank": i + 1, "level_req": min(58, level + i * level_step),
             "cost": int(round(cost * (1 + 0.28 * i))),
             "effect_value": 100 + step * i}
            for i in range(count)]


def ability(aid, name, effect_type, description, rank_table, *, cooldown=0,
            duration=0, stat_mods=None, icon=None, source=None, **extra):
    out = {
        "ability_id": f"pyromancer_{aid}",
        "name": name,
        "resource_type": "mana",
        "cooldown": cooldown,
        "effect_type": effect_type,
        "duration": duration,
        "stat_mods": stat_mods or {},
        "description": description,
        "ranks": rank_table,
        "icon_id": icon,
    }
    if source:
        out["_source"] = source
    out.update(extra)
    return out


