def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="write the files")
    args = parser.parse_args()

    # The SOURCE paragraph of this module's docstring, selected by its own
    # heading rather than by index - build_guardian.py takes paragraph [1]
    # and lands on its usage line instead, which is how guardian.json's
    # _source_note ended up reading "PYTHONPATH=. python3 ...".
    source_note = next(p for p in __doc__.strip().split("\n\n")
                       if p.startswith("SOURCE."))

    ability_doc = {
        "class": "Pyromancer",
        "_source_note": source_note.replace("\n", " "),
        "abilities": ABILITIES,
    }

    targets = [
        (ROOT / "data/abilities/pyromancer.json", ability_doc),
        (ROOT / "data/talents/pyromancer_incineration.json", INCINERATION),
        (ROOT / "data/talents/pyromancer_flameweaving.json", FLAMEWEAVING),
        (ROOT / "data/talents/pyromancer_draconic.json", DRACONIC),
    ]

    print(f"{len(ABILITIES)} abilities")
    for path, doc in targets[1:]:
        points = sum(n["max_points"] for n in doc["nodes"])
        print(f"{doc['tree_id']}: {len(doc['nodes'])} nodes, {points} points")

    if not args.apply:
        print("\n(dry run - pass --apply to write)")
        return 0

    for path, doc in targets:
        path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
