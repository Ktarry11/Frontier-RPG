# ============================================================ talent helpers

def node(tree, tid, name, description, tier, slot, max_points, effects,
         *, node_type="passive", connect=None, proc=None, source=None,
         total_slots=4):
    """One talent node. `slot` is 0-based across the tier's row.

    Hex layout copies the shipped trees: hex_y = -6 + 2*tier, hex_x spaced by
    2 and centred on the row, so tiers narrow toward the capstone.
    """
    span = (total_slots - 1) * 2
    out = {
        "talent_id": f"{tree}_{tid}",
        "name": name,
        "description": description,
        "node_type": node_type,
        "tier": tier,
        "max_points": max_points,
        "cost_per_point": 1,
        "hex_x": -span // 2 + slot * 2,
        "hex_y": -6 + 2 * tier,
        "effects": effects,
        "connected_to": [f"{tree}_{c}" for c in (connect or [])],
    }
    if proc:
        out["proc"] = proc
    if source:
        out["_source"] = source
    return out


TIER_REQUIREMENTS = {"0": 0, "1": 5, "2": 10, "3": 15, "4": 20, "5": 25, "6": 30}


def tree(tree_id, spec_name, description, nodes, source):
    return {
        "spec_name": spec_name,
        "tree_id": tree_id,
        "description": description,
        "_source_note": source,
        "tier_requirements": TIER_REQUIREMENTS,
        "nodes": nodes,
    }


def flamecasting(effect_id, trigger, chance, *, icd=1, ability_filter=None):
    """The Flamecasting proc, authored once and reused by all three trees.

    CoA's Flamecasting is "+5% spell haste for 15 seconds, stacks 5 times,
    additional applications do not refresh duration" and it is the thing that
    makes this class feel like itself - every spec has at least one talent
    that grants, extends or widens it. Nothing in the engine builds a stack
    ramp from a proc, so each tree gets ONE node that applies a flat haste
    buff instead of a five-stack climb. The per-rank scaling lands on the
    proc CHANCE, which _sync_talent_procs really does multiply by points
    spent; the payload itself does not scale with rank, so no tooltip here
    claims it does.
    """
    proc = {"trigger": trigger, "chance": chance, "icd": icd,
            "apply_effect": {
                "effect_id": f"pyromancer_{effect_id}",
                "name": "Flamecasting",
                "effect_type": "buff",
                "duration": 3,
                "stat_mods": {"haste": 6},
                "on_target": False}}
    if ability_filter:
        proc["ability_filter"] = ability_filter
    return proc


