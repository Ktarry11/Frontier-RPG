#!/usr/bin/env python3
"""Every dungeon boss acts and has something dangerous. Idempotent.

    PYTHONPATH=. python3 tools/fix_dungeon_boss_turns.py [--dry-run]

Kyle, 16 Nov 2026: "How about you screen through all dungeon bosses in the game to ensure none of them are buffing /
debuffing / punching bags". Earlier the same day: "make sure bosses are not just debuffing. they should have
something dangerous". tools/audit_boss_turns.py fights every boss for 40 turns and finds two failures:

  PASSIVE     more than 30% of its turns went on buffs, debuffs or heals that hurt nobody (and a buff or debuff it
              never used at all is a dead slot, because Monster.choose_action never spends a turn on a plain one
              while an attack is ready).
  TOOTHLESS   in 40 turns it never threw anything the party has to answer: a big hit, a party blast, a stun with a
              hammer behind it, a killing DoT, a desperation move or adds.

Dungeon bosses (world/difficulty.kind_of: a dungeon boss, a tuned dungeon boss, a hidden level's, a deep
frontier's), and with --scope open (or the default, all) the open world: field bosses, caves' (a cave that isn't a
dungeon counts its boss as a field boss), skull zones' and open frontiers'. Out there the signature is a big hit only
(1.7x every fifth turn), because a field boss is often fought by one or two.

WHAT IT DOES, in the boss's own kit in data/creatures/ability_kits.json, never a shared one:
  1. Every plain buff and debuff becomes an attack that carries it, so the effect lands and the turn still hurts
     (tools/build_scarlet_monastery_content.hit_with, the same shape): 85% of the boss's basic hit (60% if it hit
     the whole party), the same name, cooldown, school, duration and stat changes, and any shield, stun or
     mechanic it carried. A buff rides home on the boss; a debuff on whoever it hits. Low-health phase buffs
     (hp_below) are left alone: they're meant to fire once, late.
  2. A boss with nothing dangerous gets one signature move in its own school: a big hit at 1.8x its basic every
     fourth turn, or a blast across the party at 0.95x every fifth, picked by its name so the game gets both. A
     boss under level 20 gets the big hit only (1.7x, every fifth turn), so the first dungeons stay first dungeons.
     If the boss still never throws it (Monster.choose_action throws the biggest ready attack, so a blast can sit
     behind a bigger single hit forever), the second round swaps it for a big hit at 2x every third turn.
  3. If a boss is still passive after that (heals), its heals become hits that heal it for half of what they deal.
Every changed or added ability is tagged "boss_rework": "turns_pass", so a second run changes nothing.

Kits are regenerated by their zone builders and by tools/generate_creatures.py. If one of those rewrites a boss
back, tools/qa_dungeon_boss_turns.py fails and this is run again.
"""
import argparse
import contextlib
import io
import json
import os
import sys
import zlib
from pathlib import Path

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("SDL_AUDIODRIVER", "dummy")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
os.chdir(ROOT)

KITS = ROOT / "data/creatures/ability_kits.json"
CREATURES = ROOT / "data/creatures/creatures.json"
DUNGEON_KINDS = {"boss", "tuned_boss", "hidden_layer", "frontier_deep"}
#: Kyle, 16 Nov 2026, after the dungeon pass: "Yup, open world and caves next". A cave that isn't a dungeon counts
#: its boss as a field boss (world/difficulty.kind_of), so caves come with the open world.
OPEN_KINDS = {"field_boss", "skull_zone", "frontier_open"}
TAG = "turns_pass"

BIG = {"physical": ["Crushing Blow", "Skull Crack", "Brutal Cleave", "Bone-Breaker", "Savage Rend"],
       "fire": ["Searing Blast", "Pyroclasm", "Flame Lance", "Immolating Strike"],
       "frost": ["Glacial Spike", "Frostbite Lance", "Shatter", "Rime Strike"],
       "nature": ["Venom Burst", "Strangling Vines", "Corrosive Spit", "Rot Fang"],
       "shadow": ["Shadow Burst", "Soul Rend", "Grasp of Darkness", "Void Bolt"],
       "magic": ["Arcane Detonation", "Mana Lance", "Spell Rupture", "Arcane Barrage"],
       "holy": ["Judgement", "Righteous Smite", "Hammer of Wrath"]}
BLAST = {"physical": ["Whirlwind", "Ground Slam", "Cleaving Sweep"],
         "fire": ["Fire Nova", "Flame Wave"], "frost": ["Frost Nova", "Blizzard"],
         "nature": ["Poison Cloud", "Thorn Burst"], "shadow": ["Shadow Nova", "Wave of Dread"],
         "magic": ["Arcane Explosion", "Arcane Storm"], "holy": ["Consecration", "Holy Nova"]}
SCHOOL_KEY = {"arcane": "magic", "magic": "magic", "spell": "magic"}


def _school(kit):
    from collections import Counter
    c = Counter(a.get("school", "physical") for a in kit if a.get("kind", "damage") in ("damage", "dot"))
    s = (c.most_common(1)[0][0] if c else "physical") or "physical"
    s = SCHOOL_KEY.get(s, s)
    return s if s in BIG else "physical"


def _basic(kit):
    first = kit[0].get("amount") or 0
    if first:
        return first
    return max((a.get("amount", 0) for a in kit if a.get("kind", "damage") == "damage"), default=1) or 1


def _ride(a, basic):
    """A plain buff or debuff -> an attack that carries it."""
    is_buff = a.get("kind") == "buff"
    aoe = bool(a.get("is_aoe")) and not is_buff
    rider = {"effect": "buff" if is_buff else "debuff", "duration": a.get("duration", 3) or 3,
             "stat_mods": dict(a.get("stat_mods") or {})}
    for k in ("dispel_type", "mechanics"):
        if a.get(k):
            rider[k] = a[k]
    if a.get("is_stun") and not is_buff:
        rider["is_stun"] = True
    if a.get("absorb") and is_buff:
        rider["absorb"] = a["absorb"]
    out = {"name": a["name"], "kind": "damage", "amount": int(round(basic * (0.60 if aoe else 0.85))),
           "cooldown": max(3, int(a.get("cooldown", 0) or 0)), "mana_cost": a.get("mana_cost", 0),
           "school": a.get("school", "physical"), "rider": rider, "boss_rework": TAG}
    if aoe:
        out["is_aoe"] = True
    return out


def _signature(name, kit, level, basic, stronger=False, open_world=False):
    school = _school(kit)
    h = zlib.crc32(name.encode())
    taken = {a["name"] for a in kit}
    if open_world and not stronger:
        # out in the world (and in a cave) a boss is often fought by one or two: a big hit it winds up for, every
        # fifth turn, and no party blast
        names = BIG[school]
        pick = next((n for i in range(len(names)) for n in [names[(h + i) % len(names)]] if n not in taken),
                    names[h % len(names)] + " II")
        return {"name": pick, "kind": "damage", "amount": int(round(basic * 1.7)), "cooldown": 5, "mana_cost": 0,
                "school": school if school != "magic" else "arcane", "boss_rework": TAG}
    # the AI throws its biggest ready attack, so a blast that never out-hits a big hit is never thrown: the
    # stronger (second-round) signature is always a big hit
    blast = level >= 20 and h % 2 == 1 and not stronger
    names = (BLAST if blast else BIG)[school]
    pick = next((n for i in range(len(names)) for n in [names[(h + i) % len(names)]] if n not in taken),
                names[h % len(names)] + " II")
    if blast:
        return {"name": pick, "kind": "damage", "amount": int(round(basic * (1.1 if stronger else 0.95))),
                "cooldown": 4 if stronger else 5, "mana_cost": 0, "school": school if school != "magic" else "arcane",
                "is_aoe": True, "boss_rework": TAG}
    mult = (2.0 if stronger else (1.7 if level < 20 else 1.8))
    return {"name": pick, "kind": "damage", "amount": int(round(basic * mult)),
            "cooldown": (3 if stronger else (5 if level < 20 else 4)), "mana_cost": 0,
            "school": school if school != "magic" else "arcane", "boss_rework": TAG}


def _heal_to_drain(a, basic):
    return {"name": a["name"], "kind": "damage", "amount": int(round(basic * 0.9)),
            "cooldown": max(3, int(a.get("cooldown", 0) or 0)), "mana_cost": a.get("mana_cost", 0),
            "school": a.get("school", "physical"), "lifesteal": 0.5, "boss_rework": TAG}


def dungeon_bosses(cm, kinds=DUNGEON_KINDS):
    from world.difficulty import kind_of
    from entities.monster import Monster
    out = []
    for n, d in sorted(cm.creatures.items()):
        if not d.get("is_boss"):
            continue
        try:
            with contextlib.redirect_stdout(io.StringIO()):
                m = cm.spawn_creature(n, level=(d.get("level_range") or [1, 1])[-1])
        except Exception:
            continue
        if m is not None and kind_of(m) in kinds:
            out.append(n)
    return out


def failing(rows):
    from audit_boss_turns import PASSIVE_LIMIT
    return [r for r in rows if r["passive"] > PASSIVE_LIMIT or not r["dangers"] or r["dead"]]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--scope", choices=("dungeon", "open", "all"), default="all")
    a = ap.parse_args()
    kinds = {"dungeon": DUNGEON_KINDS, "open": OPEN_KINDS, "all": DUNGEON_KINDS | OPEN_KINDS}[a.scope]
    import audit_monster_combat as AMC
    import audit_boss_turns as ABT
    import entities.monster as EM
    with contextlib.redirect_stdout(io.StringIO()):
        cm = AMC._manager()
    names = dungeon_bosses(cm, kinds)
    rows, skipped = ABT.assess(names, cm)
    bad = failing(rows)
    print(f"{len(names)} bosses ({a.scope}), {len(bad)} failing "
          f"({sum(1 for r in bad if r['passive'] > ABT.PASSIVE_LIMIT)} passive, "
          f"{sum(1 for r in bad if not r['dangers'])} toothless, {sum(1 for r in bad if r['dead'])} with dead slots)")
    if a.dry_run or not bad:
        return 0
    kd = json.loads(KITS.read_text(encoding="utf-8"))
    kits = kd["kits"]
    creatures = json.loads(CREATURES.read_text(encoding="utf-8"))["creatures"]
    users = {}
    for n, c in creatures.items():
        users.setdefault(c.get("ability_kit"), []).append(n)
    changed = {}
    for rnd in (1, 2):
        for r in bad:
            n = r["name"]
            kid = creatures[n].get("ability_kit")
            if kid not in kits:
                print(f"  {n}: no kit {kid}")
                continue
            if len(users.get(kid, [])) > 1:
                print(f"  {n}: kit {kid} is shared with {users[kid]}, left alone")
                continue
            kit = kits[kid]
            basic = _basic(kit)
            notes = []
            if rnd == 1:
                for i, ab in enumerate(kit):
                    if ab.get("kind") in ("buff", "debuff") and ab.get("hp_below") is None:
                        kit[i] = _ride(ab, basic)
                        notes.append(f"{ab['name']} rides an attack")
                if not r["dangers"] and not any(ab.get("boss_rework") == TAG and ab.get("kind") == "damage"
                                                and ab["name"] not in {x["name"] for x in kit[:1]}
                                                and (ab.get("is_aoe") or ab.get("amount", 0) >= 1.6 * basic)
                                                for ab in kit):
                    sig = _signature(n, kit, r["level"], basic, open_world=r["kind"] in OPEN_KINDS)
                    kit.append(sig)
                    notes.append(f"+ {sig['name']}")
            else:
                if r["passive"] > ABT.PASSIVE_LIMIT:
                    for i, ab in enumerate(kit):
                        if ab.get("kind") == "heal" and ab.get("hp_below") is None:
                            kit[i] = _heal_to_drain(ab, basic)
                            notes.append(f"{ab['name']} drains")
                if not r["dangers"]:
                    kit[:] = [ab for ab in kit if not (ab.get("boss_rework") == TAG and "rider" not in ab
                                                       and "lifesteal" not in ab)]
                    sig = _signature(n, kit, r["level"], basic, stronger=True)
                    kit.append(sig)
                    notes.append(f"+ {sig['name']} (stronger)")
            if notes:
                changed.setdefault(n, []).extend(notes)
        KITS.write_text(json.dumps(kd, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        EM._KITS = None             # entities/monster.get_kits reads the file again
        rows, skipped = ABT.assess([r["name"] for r in bad], cm)
        bad = failing(rows)
        print(f"  after round {rnd}: {len(bad)} still failing")
        if not bad:
            break
    for n, notes in sorted(changed.items()):
        print(f"  {n}: {'; '.join(notes)}")
    if bad:
        print("STILL FAILING:")
        for r in bad:
            print(f"  {r['name']} ({r['kind']}, lvl {r['level']}): passive {r['passive']:.0%}, "
                  f"dangers {r['dangers'] or 'none'}, dead {r['dead']}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
