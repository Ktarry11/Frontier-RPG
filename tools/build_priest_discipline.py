"""Rebuild Priest Discipline from the real 3.3.5a tree.

    PYTHONPATH=. python3 tools/build_priest_discipline.py

SOURCE: data/reference/wotlk/priest.json (from Spell.dbc).
Worksheet: data/reference/wotlk_worksheets/priest.md.

ROLE: absorb-and-prevent healer. Power Word: Shield is the whole tree's
centre of gravity, with Penance as the capstone.

THIS TREE WAS ALREADY DECENT - 10 of 23 nodes carried real procs or
ability-scoped keys. The rebuild adds the five real talents it was missing
and corrects the ones wearing another talent's mechanic.

CAST TIMES ARE THE WALL. Six real Discipline talents are written on cast
time, casting-while-moving, or spell pushback: Meditation ("50% of mana
regeneration continues while casting"), Inner Focus, Improved Mana Burn,
Focused Power's Mass Dispel clause, Improved Flash Heal, Borrowed Time.
There are NO cast times in this engine at all, so each is rebuilt as the
resource or throughput the real talent exists to provide.

ABILITIES THE REAL TREE WANTS AND WE LACK: Flash Heal, Greater Heal, Mana
Burn, Mass Dispel, Prayer of Fortitude, Cure Disease. Talents written on
those are re-aimed at priest_heal, which is this kit's one direct heal, or
dropped. Improved Mana Burn is DROPPED outright - there is no Mana Burn
and nothing resembling it.

UNIT CONVENTIONS, probed: intellect_pct / spirit_pct / haste /
crit_chance_spell / stamina_pct are PERCENTAGE POINTS; spell_damage /
healing_done / threat_generation_pct / all_ability_cost_pct /
stun_duration_reduction_pct / low_health_damage_reduction_pct are
FRACTIONS; all_ability_cost_pct is POSITIVE-IS-A-REDUCTION and FLIPS to
points inside a status effect; mp5 is FLAT.

low_health_threshold_pct is authored NOWHERE (the kit refuses it). The
outgoing Pain Suppression authored it, which is why it is absent here.

KEPT MANDATORY: Penance is the only unlock for priest_penance, which is
requires_talent.
"""

