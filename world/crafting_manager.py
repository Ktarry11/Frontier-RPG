"""
Generic crafting stations: Alchemy, Tailoring, Woodworking, and the Sawmill (Woodcutting's logs -> planks).

Recipes live in data/crafting/recipes.json (generated by tools/build_crafting_professions.py).  Every recipe has a
skill_required, a dict of inputs (material id -> qty) and an output spec:

  material    -> a stackable Material (planks, fiber, pages, bolts, upgrade kits); `count` units per craft
  consumable  -> a Consumable from data/consumables (potions, elixirs, arrows/bolts); `count` units per craft
  armor/weapon-> procedural Item from LootGenerator (same stat budget math as every drop), is_crafted=True
  bag         -> a bag from data/items/bags.json

Rules (same as Smelting / Blacksmithing): guaranteed success, skill only gates ACCESS; the profession must be LEARNED
from a trainer (Character.knows_profession); skill-ups roll against the recipe's [orange, yellow, green, grey] range and
never pass the trained tier's cap.  The Sawmill recipes also need the player to be standing at a sawmill.
"""
import json
import random
from pathlib import Path

_DATA = Path(__file__).parent.parent / "data" / "crafting" / "recipes.json"
#: Jewelcrafting keeps its own file (tools/build_jewelcrafting.py), read in alongside the rest.
_JEWEL = Path(__file__).parent.parent / "data" / "jewelcrafting" / "recipes.json"
_GEAR_KINDS = ("armor", "weapon", "bag", "fixed")


class CraftingManager:
    def __init__(self):
        self.recipes = {}   # profession -> {recipe_id: recipe}
        if _DATA.exists():
            doc = json.loads(_DATA.read_text(encoding="utf-8"))
            self.recipes = {p: v.get("recipes", {}) for p, v in doc.get("professions", {}).items()}
        if _JEWEL.exists():
            self.recipes["jewelcrafting"] = json.loads(_JEWEL.read_text(encoding="utf-8")).get("recipes", {})

    # ------------------------------------------------------------------ queries
    def professions(self):
        return list(self.recipes)

    def all_recipes(self, profession):
        return self.recipes.get(profession, {})

    def skill(self, character, profession):
        return character.profession_skills.get(profession, 0)

    def available_recipes(self, character, profession):
        """Recipes the character may craft right now: profession learned + skill high enough + recipe known.

        Trainer-source recipes are auto-taught on trainer visit (character.learn_trainer_recipes).
        Drop/vendor/quest recipes must be explicitly learned by using a recipe scroll item.
        Both paths ultimately write to character.known_recipes; this filter trusts that set.
        """
        if not character.knows_profession(profession):
            return {}
        skill = self.skill(character, profession)
        return {
            rid: r for rid, r in self.all_recipes(profession).items()
            if skill >= r.get("skill_required", 0) and character.knows_recipe(rid)
        }

    def can_craft(self, character, profession, recipe_id):
        r = self.all_recipes(profession).get(recipe_id)
        if r is None or not character.knows_profession(profession):
            return False
        if not character.knows_recipe(recipe_id):
            return False
        if self.skill(character, profession) < r.get("skill_required", 0):
            return False
        if r.get("tool") and character.get_material_quantity(r["tool"]) < 1:
            return False
        return character.has_materials(r["inputs"])

    def output_name(self, recipe):
        n = recipe.get("count", 1)
        return recipe["name"] if n == 1 or "(" in recipe["name"] else f"{recipe['name']} x{n}"

    # ------------------------------------------------------------------ crafting
    def craft(self, character, profession, recipe_id, at_station=True):
        """-> (ok, message, output).  Output is the Item / Material / Consumable produced (None on failure)."""
        r = self.all_recipes(profession).get(recipe_id)
        if r is None:
            return False, "Unknown recipe.", None
        if not character.knows_profession(profession):
            return False, f"You haven't learned {profession.title()}.", None
        if self.skill(character, profession) < r.get("skill_required", 0):
            return False, f"Requires {profession.title()} skill {r['skill_required']}.", None
        if r.get("station") == "sawmill" and not at_station:
            return False, "You must be at a Sawmill to saw planks.", None
        if r.get("tool") and character.get_material_quantity(r["tool"]) < 1:
            # a tool is needed in the bags but never used up (the Jeweler's Kit)
            from world.gathering_manager import get_gathering_node_manager
            tool = get_gathering_node_manager().get_material_def(r["tool"]) or {}
            return False, f"You need a {tool.get('name', r['tool'])} in your bags.", None
        if not character.has_materials(r["inputs"]):
            return False, "Missing materials for that recipe.", None
        out = r["output"]
        if out["kind"] in _GEAR_KINDS and len(character.inventory) >= character.inventory_capacity:
            return False, "Your bags are full.", None

        product = self._make_output(r)
        if product is None:
            return False, "That recipe is broken (no output).", None
        for mid, qty in r["inputs"].items():
            character.consume_material(mid, qty)

        if out["kind"] == "prospect":
            for m in product:
                character.add_material(m)
        elif out["kind"] == "material":
            character.add_material(product)
        elif out["kind"] == "consumable":
            character.add_consumable(product)
        else:
            if not character.add_to_inventory(product):
                return False, "Your bags are full.", None

        self._skill_up(character, profession, r)
        self._award_craft_xp(character, r)
        try:
            from world.quest_manager import get_quest_manager
            get_quest_manager().record_craft(recipe_id)
            if out["kind"] == "material":
                get_quest_manager().record_craft(out["material_id"])
        except Exception:
            pass
        if out["kind"] == "prospect":
            found = ", ".join(f"{m.name}" + (f" x{m.quantity}" if m.quantity > 1 else "") for m in product)
            return True, f"Prospected: {found}.", product
        return True, f"Crafted {self.output_name(r)}.", product

    def _award_craft_xp(self, character, recipe):
        """Award a small amount of character XP for completing a craft.

        Calibration: crafting should be a supplement to combat XP, not a
        replacement. A recipe whose output sits at item_level N awards about
        the same XP as killing a level-N mob would give a same-level player
        (i.e. 1-2% of the XP needed to level at that point). For material
        outputs (bolts, upgrade kits) we use skill_required as a proxy for
        difficulty, mapping it to a rough item_level equivalent.
        """
        try:
            from config import get_exp_needed_for_level
            out = recipe["output"]
            # Determine the effective item level for XP calculation
            item_level = out.get("item_level")
            if item_level is None:
                # Material/consumable recipes: derive item_level from skill_required
                # skill 0 = level 1, skill 300 = level 60 (WoW-like linear mapping)
                skill = recipe.get("skill_required", 0)
                item_level = max(1, int(skill * 60 / 300) + 1)
            # XP ≈ 2% of exp needed to go from item_level to item_level+1
            xp = max(5, int(get_exp_needed_for_level(max(1, item_level)) * 0.02))
            character.gain_experience(xp)
        except Exception:
            pass

    def _skill_up(self, character, profession, recipe):
        skill = self.skill(character, profession)
        req = recipe.get("skill_required", 0)
        orange, yellow, green, grey = recipe.get("skill_range") or (req + 5, req + 15, req + 25, req + 35)
        if skill >= grey:
            return False
        if skill < orange:
            chance = 1.0
        elif skill < yellow:
            chance = 0.75
        elif skill < green:
            chance = 0.35
        else:
            chance = 0.10
        if random.random() < chance:
            return character.gain_profession_skill(profession, 1)
        return False

    def _make_output(self, recipe):
        out = recipe["output"]
        kind = out["kind"]
        count = recipe.get("count", 1)
        if kind == "material":
            from world.gathering_manager import get_gathering_node_manager
            m = get_gathering_node_manager().make_material_instance(out["material_id"])
            if m is not None:
                m.quantity = count
            return m
        if kind == "prospect":
            return self._prospect(out["ore"])
        if kind == "fixed":
            # a hand-authored item (the jewelcrafting figurines): its stats and proc are written
            # out in the recipe, the same shape a boss's fixed drop uses
            from entities.boss_loot import _item_from_def
            item = _item_from_def(out["item"])
            item.is_crafted = True
            return item
        if kind == "consumable":
            from entities.consumable_manager import get_consumable_manager
            return get_consumable_manager().get_consumable(out["consumable_id"], count)
        from entities.loot_generator import LootGenerator
        gen = LootGenerator()
        if kind == "bag":
            item = gen.generate_bag(bag_id=out["bag_id"])
            if item is not None:
                item.is_crafted = True
            return item
        if kind == "armor":
            item = gen.generate_armor_piece(slot=out["slot"], armor_type=out["armor_type"], stat_template=out["stat_template"],
                                            item_level=out["item_level"], rarity=out["rarity"])
        elif kind == "weapon":
            item = gen.generate_weapon(slot=out["slot"], weapon_type=out["weapon_type"], stat_template=out["stat_template"],
                                       item_level=out["item_level"], rarity=out["rarity"])
        else:
            return None
        item.is_crafted = True
        item.name = recipe["name"]
        item.crafting_material = out.get("material_tier")
        return item


    #: Prospecting five ore always turns up a stone, sometimes two. Each of the ore's stones is
    #: weighted by how often a miner finds it, so the rare one stays the rare one.
    PROSPECT_SECOND = 0.3

    def _prospect(self, ore_id):
        from world.gathering_manager import get_gathering_node_manager
        gm = get_gathering_node_manager()
        table = gm.gem_table().get(ore_id, [])
        if not table:
            return None
        found = {}
        for _ in range(1 + (1 if random.random() < self.PROSPECT_SECOND else 0)):
            gid = random.choices([g for g, _c in table], weights=[c for _g, c in table])[0]
            found[gid] = found.get(gid, 0) + 1
        out = []
        for gid, n in found.items():
            m = gm.make_material_instance(gid)
            if m is not None:
                m.quantity = n
                out.append(m)
        return out


_crafting_manager = None


def get_crafting_manager():
    global _crafting_manager
    if _crafting_manager is None:
        _crafting_manager = CraftingManager()
    return _crafting_manager
